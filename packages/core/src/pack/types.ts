import type { PackUserConfig, TsdownPluginOption } from 'vite-plus/pack';

import type { NOmit } from '#utils/types';

import type { DEFAULT_PLUGINS } from './plugins';

/**
 * Output formats supported by Vite+ Pack.
 */
export type PackFormat = 'esm' | 'cjs' | 'iife' | 'umd';

/**
 * Declaration file generators supported by Vite+ Pack.
 */
export type DtsGenerator = 'tsc' | 'oxc' | 'tsgo';

/**
 * Declaration file options of Vite+ Pack.
 */
export type DtsOptions = PackUserConfig['dts'];

/**
 * Configuration parameters for Vite+ Pack configuration generation.
 */
export type Params = {
  circularDeps?: string | string[];
  excludesTS?: string | string[];
  externals?: string | string[];
  ignoresJS?: string | string[];
  dir?: string;
  sourcemap?: boolean;
  dts?: DtsOptions;
  plugins?: (TsdownPluginOption | keyof typeof DEFAULT_PLUGINS)[];
} & NOmit<
  PackUserConfig,
  | keyof PackOutput
  | 'entry'
  | 'platform'
  | 'dts'
  | 'external'
  | 'plugins'
  | 'sourcemap'
>;

/**
 * Function type building the entry points record from glob patterns.
 */
export type BuildEntry_F = (...ignores: string[]) => Record<string, string>;

/**
 * Output options shared by every bundle generated by Vite+ Pack.
 */
export type PackOutput = Pick<
  PackUserConfig,
  'outDir' | 'format' | 'unbundle' | 'fixedExtension' | 'sourcemap'
>;

/**
 * Vite+ Pack configuration generator with predefined presets
 * (`bemedev`, `fast`, `default`).
 */
export type Config_F = {
  (additionals?: Params): PackUserConfig;
  bemedev: (additionals?: Params) => PackUserConfig;
  fast: (additionals?: Omit<Params, 'plugins' | 'dts'>) => PackUserConfig;
  default: (additionals?: Params) => PackUserConfig;
};
